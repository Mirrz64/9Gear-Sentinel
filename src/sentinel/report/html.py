def render_report(run: StoredRun) -> str:
    counts = Counter(result.status for result in run.results)
    ordered = sorted(run.results, key=lambda r: (_ORDER.index(r.status), r.table_name, r.label))
    when = run.started_at.strftime("%Y-%m-%d %H:%M UTC")

    stats = "".join(
        f'<div class="stat"><b>{counts.get(status, 0)}</b><span>{label}</span></div>'
        for status, label in (
            ("PASS", "passed"),
            ("FAIL", "failed"),
            ("WARN", "warnings"),
            ("ERROR", "errors"),
        )
    )

    rows = []
    for result in ordered:
        trend = run.trends.get(f"{result.table_name}:{result.label}", [result.status])
        dots = "".join(f'<span class="dot {status}" title="{status}"></span>' for status in trend)
        rows.append(
            "<tr>"
            f'<td><span class="badge {result.status}">{result.status}</span></td>'
            f"<td>{escape(result.table_name)}</td>"
            f'<td class="check">{escape(result.label)}</td>'
            f"<td>{escape(result.message)}</td>"
            f'<td><div class="trend" aria-label="last {len(trend)} runs">'
            f"{dots}</div></td>"
            "</tr>"
        )

    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>9Gear Sentinel report, {escape(when)}</title>
<style>{_CSS}</style>
</head>
<body>
<main>
<header>
<img class="light" src="{_icon("light")}" alt="">
<img class="dark" src="{_icon("dark")}" alt="">
<div>
<h1>Data quality report</h1>
<p>Run at {escape(when)} &middot; {len(run.results)} checks
&middot; status: {escape(run.status)}</p>
</div>
</header>
<section class="summary">{stats}</section>
<div class="table-wrap">
<table>
<thead><tr>
<th>Status</th><th>Table</th><th>Check</th><th>Result</th><th>Recent runs</th>
</tr></thead>
<tbody>
{"".join(rows)}
</tbody>
</table>
</div>
<footer>Generated by 9Gear Sentinel {escape(__version__)}.
Recent runs read oldest to newest.</footer>
</main>
</body>
</html>
"""
